/**
 * Extracts the handful of icons the video uses from the (11 MB) Iconify sets
 * into kit/design/icons-data.ts, so the Remotion bundle stays small.
 * Same sets the site uses: Solar for UI/diagram icons, MDI for brand marks.
 *
 *   npm run icons
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const WANTED: Record<'solar' | 'mdi', string[]> = {
  solar: [
    'alt-arrow-right-linear',
    'arrow-right-linear',
    'bolt-bold',
    'bomb-bold-duotone',
    'box-bold',
    'bug-bold',
    'camera-rotate-bold-duotone',
    'check-circle-bold',
    'close-circle-bold',
    'cloud-bold',
    'cloud-storage-bold',
    'code-square-bold',
    'compass-square-bold-duotone',
    'compass-square-line-duotone',
    'copy-line-duotone',
    'cpu-bold',
    'cpu-bolt-bold',
    'danger-bold',
    'database-bold',
    'dollar-bold',
    'gamepad-bold',
    'global-bold',
    'graph-up-bold',
    'key-bold',
    'layers-bold',
    'lock-keyhole-bold',
    'monitor-bold',
    'moon-sleep-bold',
    'plug-circle-bold-duotone',
    'power-bold',
    'programming-bold',
    'rocket-2-bold',
    'screencast-bold',
    'server-2-bold',
    'server-bold',
    'server-square-bold',
    'server-square-cloud-bold-duotone',
    'shield-bold',
    'shield-check-bold',
    'shield-check-bold-duotone',
    'shield-keyhole-bold',
    'snowflake-line-duotone',
    'stopwatch-bold',
    'test-tube-bold',
    'transfer-horizontal-bold',
    'user-rounded-bold',
    'verified-check-bold',
    'widget-bold',
  ],
  mdi: ['docker', 'kubernetes', 'linux', 'google-chrome', 'nodejs', 'language-python', 'console'],
};

type IconSet = { width?: number; height?: number; icons: Record<string, { body: string; width?: number; height?: number }> };

const out: Record<string, { body: string; w: number; h: number }> = {};
for (const [prefix, names] of Object.entries(WANTED)) {
  const set = JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8')) as IconSet;
  for (const name of names) {
    const icon = set.icons[name];
    if (!icon) {
      throw new Error(`Icon ${prefix}:${name} not found`);
    }
    out[`${prefix}:${name}`] = { body: icon.body, w: icon.width ?? set.width ?? 24, h: icon.height ?? set.height ?? 24 };
  }
}

const file = `// Generated by scripts/extract-icons.ts — do not edit by hand.
// Solar (https://github.com/480-Design/Solar-Icon-Set, CC BY 4.0) and
// Material Design Icons (Apache 2.0), via Iconify.

export const ICONS = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;

writeFileSync(new URL('../kit/design/icons-data.ts', import.meta.url), file);
console.log(`Wrote ${Object.keys(out).length} icons to kit/design/icons-data.ts`);
